CREATE SCHEMA IF NOT EXISTS raw;

CREATE TABLE IF NOT EXISTS raw.orders (
    order_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number     VARCHAR(32)    NOT NULL UNIQUE,
    relation_id      BIGINT         NOT NULL REFERENCES raw.relations (relation_id),
    order_status     VARCHAR(20)    NOT NULL CHECK (order_status IN (
                         'draft', 'confirmed', 'shipped', 'delivered', 'cancelled', 'returned'
                     )),
    currency_code    CHAR(3)        NOT NULL CHECK (currency_code IN ('EUR', 'GBP', 'USD')),
    subtotal_amount  NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (subtotal_amount >= 0),
    discount_amount  NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (discount_amount >= 0),
    tax_amount       NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (tax_amount >= 0),
    shipping_amount  NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (shipping_amount >= 0),
    total_amount     NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (total_amount >= 0),
    ordered_at       TIMESTAMPTZ    NOT NULL,
    shipped_at       TIMESTAMPTZ,
    delivered_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    CHECK (shipped_at IS NULL OR shipped_at >= ordered_at),
    CHECK (delivered_at IS NULL OR (shipped_at IS NOT NULL AND delivered_at >= shipped_at))
);

CREATE INDEX IF NOT EXISTS idx_orders_relation_id  ON raw.orders (relation_id);
CREATE INDEX IF NOT EXISTS idx_orders_status       ON raw.orders (order_status);
CREATE INDEX IF NOT EXISTS idx_orders_ordered_at   ON raw.orders (ordered_at);
CREATE INDEX IF NOT EXISTS idx_orders_updated_at   ON raw.orders (updated_at);

CREATE TABLE IF NOT EXISTS raw.order_items (
    order_item_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          BIGINT         NOT NULL REFERENCES raw.orders (order_id) ON DELETE CASCADE,
    line_number       INTEGER        NOT NULL CHECK (line_number >= 1),
    sku               VARCHAR(32)    NOT NULL,
    product_name      VARCHAR(200)   NOT NULL,
    product_category  VARCHAR(80)    NOT NULL,
    quantity          INTEGER        NOT NULL CHECK (quantity >= 1),
    unit_price        NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    discount_pct      NUMERIC(5, 2)  NOT NULL DEFAULT 0.00 CHECK (discount_pct >= 0 AND discount_pct <= 100),
    tax_rate_pct      NUMERIC(5, 2)  NOT NULL DEFAULT 21.00 CHECK (tax_rate_pct >= 0),
    line_subtotal     NUMERIC(12, 2) NOT NULL CHECK (line_subtotal >= 0),
    line_discount     NUMERIC(12, 2) NOT NULL CHECK (line_discount >= 0),
    line_tax          NUMERIC(12, 2) NOT NULL CHECK (line_tax >= 0),
    line_total        NUMERIC(12, 2) NOT NULL CHECK (line_total >= 0),
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    UNIQUE (order_id, line_number)
);

CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON raw.order_items (order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_sku      ON raw.order_items (sku);
