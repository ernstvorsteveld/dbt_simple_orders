CREATE SCHEMA IF NOT EXISTS raw;

CREATE TABLE IF NOT EXISTS raw.relations (
    relation_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_ref    VARCHAR(32)  NOT NULL UNIQUE,
    relation_type   VARCHAR(20)  NOT NULL CHECK (relation_type IN ('person', 'organization')),
    relation_role   VARCHAR(20)  NOT NULL CHECK (relation_role IN ('customer', 'supplier', 'partner', 'prospect')),
    display_name    VARCHAR(200) NOT NULL,
    first_name      VARCHAR(100),
    last_name       VARCHAR(100),
    company_name    VARCHAR(200),
    tax_id          VARCHAR(50),
    email           VARCHAR(255),
    phone           VARCHAR(40),
    street_address  VARCHAR(200),
    postal_code     VARCHAR(20),
    city            VARCHAR(100),
    country_code    CHAR(2)      NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive', 'blocked')),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_relations_type_role  ON raw.relations (relation_type, relation_role);
CREATE INDEX IF NOT EXISTS idx_relations_country    ON raw.relations (country_code);
CREATE INDEX IF NOT EXISTS idx_relations_updated_at ON raw.relations (updated_at);
